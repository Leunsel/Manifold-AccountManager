"""Generate Source/Generated/CsvKat.h: CSV quoting cases with the expected
output of Python's csv module (RFC 4180, QUOTE_MINIMAL).
"""
import csv
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'Manifold-Vault', 'Source', 'Generated',
                   'CsvKat.h')

CORPUS = [
    '',
    'plain',
    'with,comma',
    'with"quote',
    'both,"mixed"',
    'line\nbreak',
    'line\r\nbreak',
    'bare\rcarriage return',
    '""',
    '"fully enclosed"',
    'a,b,c,d',
    'umlauts: äöüß',
    'P@ssw0rd!#$%&/()=?',
    '=SUM(A1:A9)',
    '+491701234567',
    '-minus',
    '@mention',
    'Tab\there',
    ',',
    ',,',
    '"',
    '""""',
    'x' * 300,
]

def quoted(value):
    buffer = io.StringIO()
    writer = csv.writer(buffer, quoting=csv.QUOTE_MINIMAL, lineterminator='')
    writer.writerow(['x', value])
    text = buffer.getvalue()
    assert text.startswith('x,'), text
    return text[2:]

def escape(value):
    out = []
    for ch in value.encode('utf-8'):
        if ch == 0x22:
            out.append('\\"')
        elif ch == 0x5C:
            out.append('\\\\')
        elif 0x20 <= ch < 0x7F:
            out.append(chr(ch))
        else:
            out.append('\\x%02X""' % ch)
    return ''.join(out)

rows = []
for raw in CORPUS:
    assert not raw.startswith(' ') and not raw.endswith(' '), \
        'edge spaces do not belong in this corpus: %r' % raw
    q = quoted(raw)
    back = next(csv.reader(['x,' + q]))
    assert back == ['x', raw], \
        'round trip mismatch: %r -> %r -> %r' % (raw, q, back)
    rows.append((raw, q))

lines = [
    '// Generated by Tools/gen_csv_kat.py from Python\'s csv module (RFC 4180). Do not edit.',
    '#pragma once',
    '',
    'namespace Bunker::Kat',
    '{',
    '    struct CsvCase { const char* Raw; const char* Quoted; };',
    '',
    '    inline constexpr CsvCase kCsvQuoting[] = {',
]
for raw, q in rows:
    lines.append('        { "%s", "%s" },' % (escape(raw), escape(q)))
lines.append('    };')
lines.append('}')

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with io.open(OUT, 'w', encoding='utf-8', newline='\r\n') as f:
    f.write('\n'.join(lines) + '\n')
print('%d cases -> %s' % (len(rows), os.path.normpath(OUT)))
